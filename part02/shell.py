# 셸(Shell) 명령어
# - 셸(Shell)은 사용자가 입력한 명령어를 해석하여 운영체제의 핵심인 커널(Kernel)에 전달하고, 그 실행 결과를 사용자에게 돌려주는 명령어 해석기이자 인터페이스 프로그램이다.

# pwd(print working directory) : 현재 작업 디렉토리(경로) 출력
# ls(list segements) : 현재 작업 디렉토리(경로)에 있는 파일과 폴더 목록 출력
# cd(change directory) : 현재 작업 디렉토리(경로) 변경(이동)
# cp(copy) : 파일을 다른 이름의 파일로 복사
# mv(move) : 파일을 다른 이름의 파일로 이동(이름 변경)
# rm(remove) : 파일 삭제 🚨삭제시 휴지통으로 이동되지않고 바로 삭제되므로 주의해서 사용하기!!
