# 블럭문
# - 블럭문 안에 또 다른 블럭문이 들어갈 수도 있음
if True: #이 부분이 False이면 블럭 안의 모든 코드라인이 실행되지 않음
    print('블럭에 속한 코드입니다') #이 코드라인이 블럭에 속함

    if False:
        print('한 줄 더 얍!')

    if True:    
        print('또 한 줄 더')

    print('블럭의 끝에 있는 코드입니다') #이 코드라인도 블럭에 속함

print('블럭 밖에 있는 코드입니다') #이 코드라인은 블럭에 속하지 않음

if False:
    print('조건에 맞지 않는 코드')

    if True:
        print('조건이 맞지만 실행되지 않는 코드')

    print('여전히 실행되지 않는 코드')

print('블럭 밖에 있는 코드 두번째')